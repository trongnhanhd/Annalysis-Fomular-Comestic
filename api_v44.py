"""V4.4 FastAPI, V4.3 routes retained in same application.
Every response is a screening tool, not authorization to manufacture or market a product.
"""
import os
from fastapi import FastAPI,HTTPException,Query
from fastapi.routing import APIRoute
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel,ConfigDict,Field
from api_v43 import app as v43_app
from optimizer_v44 import solve_scenario, solve_claim_alternatives, InputError
from formula_group_service import Catalog
from scientific_bridge_v44 import screen_representative

catalog=Catalog()
app=FastAPI(title='Formula Intelligence V4.4 — Group and Concentration Optimizer',version='4.4.0')
app.add_middleware(CORSMiddleware,allow_origins=[s.strip() for s in os.getenv('RND_ALLOWED_ORIGINS','http://localhost:3000').split(',') if s.strip()],allow_methods=['GET','POST'],allow_headers=['Content-Type'])
class InputScenario(BaseModel):
    model_config=ConfigDict(extra='allow')
    items:list[dict]=Field(min_length=1,max_length=60)
    claims:list[dict]=Field(default_factory=list,max_length=40)
    ambiguous_claims:list[dict]=Field(default_factory=list,max_length=3)
    group_limits:list[dict]=Field(default_factory=list,max_length=50)
    product_id:int|None=None
    template_mode:str='advisory'
    label_inci_order:list[str]=Field(default_factory=list,max_length=150)
    label_order_known_above_one:list[str]=Field(default_factory=list,max_length=150)

@app.get('/health/v4.4')
def health_v44():
    return {'ok':True,'version':'4.4.0','approved_for_manufacturing':False,'legal_review':'NOT_ASSESSED'}

@app.get('/api/v4.4/templates')
def templates():
    return {'total':len(catalog.products),'results':list(catalog.products.values())}

@app.get('/api/v4.4/groups')
def groups(product_id:int=Query(...,ge=1)):
    return {'product_id':product_id,'results':[r for (p,_),r in catalog.product_rules.items() if p==product_id]}

@app.post('/api/v4.4/optimize')
def optimize(body:InputScenario):
    try:
        payload=body.model_dump()
        result=solve_scenario(payload,catalog if body.product_id is not None else None)
        if payload.get('include_scientific_screening') and result.get('status')=='FEASIBLE':
            result['scientific_screening']=screen_representative(payload,result)
        return result
    except (ValueError,InputError) as e:raise HTTPException(status_code=422,detail=str(e))

@app.post('/api/v4.4/compare-claims')
def compare(body:InputScenario):
    try:
        payload=body.model_dump()
        result=solve_claim_alternatives(payload,catalog if body.product_id is not None else None)
        if payload.get('include_scientific_screening'):
            for variant in result['scenarios']:
                if variant['result'].get('status')=='FEASIBLE':
                    variant['result']['scientific_screening']=screen_representative(payload,variant['result'])
        return result
    except (ValueError,InputError) as e:raise HTTPException(status_code=422,detail=str(e))

# Retain V4.3 API operations, but not its autogenerated /docs/openapi routes.
# A single application must expose exactly one OpenAPI schema.
for route in v43_app.router.routes:
    if isinstance(route, APIRoute):
        app.router.routes.append(route)

